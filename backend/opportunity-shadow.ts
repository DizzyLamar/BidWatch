export type LegacyOpportunityIdentity = {
  id: string;
  sourceId: string;
  state?: string;
};

export type CanonicalOpportunityIdentity = {
  canonical_key: string;
  state: string;
};

export type OpportunityShadowComparison = {
  legacyCount: number;
  canonicalCount: number;
  matchedCount: number;
  missingCanonicalCount: number;
  unmatchedCanonicalCount: number;
  stateMismatchCount: number;
  duplicateCanonicalKeyCount: number;
  complete: boolean;
};

/**
 * Compare the deterministic Phase 2B mapping without returning procurement
 * content or changing either read path. The canonical key is generated by the
 * backfill as legacy:<sourceId>:<legacyRecordId>.
 */
export function buildOpportunityShadowComparison(
  legacy: LegacyOpportunityIdentity[],
  canonical: CanonicalOpportunityIdentity[],
  complete = true,
): OpportunityShadowComparison {
  const canonicalByKey = new Map<string, CanonicalOpportunityIdentity>();
  const duplicateKeys = new Set<string>();

  for (const item of canonical) {
    if (canonicalByKey.has(item.canonical_key)) duplicateKeys.add(item.canonical_key);
    else canonicalByKey.set(item.canonical_key, item);
  }

  let matchedCount = 0;
  let stateMismatchCount = 0;
  for (const item of legacy) {
    const key = `legacy:${item.sourceId}:${item.id}`;
    const target = canonicalByKey.get(key);
    if (!target) continue;
    matchedCount += 1;

    const expectedState = item.state === 'imported'
      ? 'converted'
      : item.state === 'dismissed'
        ? 'dismissed'
        : 'new';
    if (target.state !== expectedState) stateMismatchCount += 1;
  }

  return {
    legacyCount: legacy.length,
    canonicalCount: canonical.length,
    matchedCount,
    missingCanonicalCount: legacy.length - matchedCount,
    unmatchedCanonicalCount: Math.max(0, canonicalByKey.size - matchedCount),
    stateMismatchCount,
    duplicateCanonicalKeyCount: duplicateKeys.size,
    complete,
  };
}
